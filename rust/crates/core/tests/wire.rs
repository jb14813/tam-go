use r_tam_core::{
    models::{BackupFile, Form, SaveBatch, Ticket},
    wire,
};

#[test]
fn go_json_preserves_struct_order_escaping_and_omits_zero_revision() {
    let row: Ticket =
        wire::decode("{\"prefix\":\"<&>\u{2028}\u{2029}\",\"t_id\":4,\"rev\":0}".as_bytes())
            .unwrap();
    assert_eq!(wire::go_json(&row).unwrap(), br#"{"prefix":"\u003c\u0026\u003e\u2028\u2029","t_id":4,"first_name":"","last_name":"","phone_number":"","pref":""}"#);
    assert_eq!(
        wire::go_json(&BackupFile::default()).unwrap(),
        br#"{"prefixes":[],"baskets":[],"tickets":[]}"#
    );
}

#[test]
fn canonical_save_includes_base_after_model_and_preserves_duplicate_rows() {
    let mut rows = SaveBatch::decode(Form::Baskets, br#"[{"prefix":" A ","b_id":3,"description":"tea","rev":7,"win_rev":8,"base":{"description":"old"}},{"prefix":" A ","b_id":3}]"#).unwrap();
    rows.validate().unwrap();
    assert_eq!(wire::go_json(&rows).unwrap(), br#"[{"prefix":"A","b_id":3,"description":"tea","donors":"","winning_ticket":0,"rev":7,"win_rev":8,"base":{"description":"old","donors":""}},{"prefix":"A","b_id":3,"description":"","donors":"","winning_ticket":0}]"#);
}

#[test]
fn query_encoding_sorts_decoded_keys_keeps_value_order_and_go_escaping() {
    assert_eq!(
        wire::canonical_query(
            "z=last&a=two+words&a=one&%C3%A9=%2f%3f&b=~!*()&bad=%zz&semi=x;y&empty"
        ),
        "a=two+words&a=one&b=~%21%2A%28%29&empty=&z=last&%C3%A9=%2F%3F"
    );
}

#[test]
fn ordered_save_digest_is_a_literal_sha256_vector() {
    assert_eq!(
        wire::save_digest("DELETE", "/prefixes", "z=last&p=A+%26+B&p=C", b"null"),
        "6e577f2316a85041170460ab36f7457f8b14bec88c9e745e25b49dfa149e0d3f"
    );
    let mut rows = SaveBatch::decode(
        Form::Tickets,
        br#"[{"t_id":0,"prefix":" A ","pref":" CALL ","base":{"pref":" TEXT "}}]"#,
    )
    .unwrap();
    rows.validate().unwrap();
    assert_eq!(
        wire::save_digest(
            "POST",
            "/api/tickets",
            "b=2&a=first&a=second",
            &wire::go_json(&rows).unwrap()
        ),
        "338aada56e99f45b8c90c31d9eea8d8e3cd124fa465702b8e6a20b49e30dbaef"
    );
}

#[test]
fn composite_digest_matches_the_actual_go_oracle() {
    // Generated by rust/tests/compatibility/digest_oracle.go using the pinned
    // Go validators and encoder, rather than another Rust implementation.
    let mut saves = SaveBatch::decode(Form::Baskets, r#"[{"prefix":" A &é ","b_id":3,"description":" <tea>&\u2028\u2029😀 ","donors":" Local ","winning_ticket":4,"rev":7,"win_rev":8,"base":{"description":" old ","donors":" Before "}},{"prefix":" A &é ","b_id":3}]"#.as_bytes()).unwrap();
    saves.validate().unwrap();
    let encoded = wire::go_json(&saves).unwrap();
    assert_eq!(
        String::from_utf8(encoded.clone()).unwrap(),
        r#"[{"prefix":"A \u0026é","b_id":3,"description":" \u003ctea\u003e\u0026\u2028\u2029😀 ","donors":" Local ","winning_ticket":4,"rev":7,"win_rev":8,"base":{"description":" old ","donors":" Before "}},{"prefix":"A \u0026é","b_id":3,"description":"","donors":"","winning_ticket":0}]"#
    );
    assert_eq!(
        wire::save_digest(
            "POST",
            "/api/baskets",
            "z=last&a=two+words&a=one&%C3%A9=%2f%3f&b=~!*()&bad=%zz&semi=x;y&empty",
            &encoded
        ),
        "723972adb200775d772d9dcea9609fdd1f08b657546e15342b319604228fa948"
    );
}

#[test]
fn decode_replaces_invalid_utf8_and_lone_surrogates_like_go() {
    let row: Ticket =
        wire::decode(br#"{"t_id":1,"prefix":"\ud800x\udc00","first_name":"\ud83d\ude00"}"#)
            .unwrap();
    assert_eq!(row.prefix, "\u{fffd}x\u{fffd}");
    assert_eq!(row.first_name, "😀");
    let mut raw = br#"{"t_id":1,"prefix":""#.to_vec();
    raw.extend_from_slice(&[0xf0, 0x90, 0xff]);
    raw.extend_from_slice(br#""}"#);
    assert_eq!(
        wire::decode::<Ticket>(&raw).unwrap().prefix,
        "\u{fffd}\u{fffd}\u{fffd}"
    );
}
